/// Which abbreviations a name expands: "St" is Saint in a place name and
/// Street in an address.
enum NameRules { places, addresses }

/// Normalizes a name for search, exactly as the build normalizes the names
/// it stores (README.md, test/normalize_vectors.json): apostrophes go, "&"
/// reads "and", accented Latin letters fold to ASCII, case goes, anything
/// else that isn't a letter or digit splits words, and abbreviations expand.
String normalizeName(String name, NameRules rules) {
  final out = StringBuffer();
  for (final rune in name.runes) {
    final c = String.fromCharCode(rune);
    if (_apostrophes.contains(c)) continue;
    if (c == '&') {
      out.write(' and ');
      continue;
    }
    final folded = _fold[c] ?? c;
    for (final unit in folded.toLowerCase().codeUnits) {
      final isWordChar =
          (unit >= 0x61 && unit <= 0x7a) || (unit >= 0x30 && unit <= 0x39);
      out.writeCharCode(isWordChar ? unit : 0x20);
    }
  }
  final abbreviations = switch (rules) {
    NameRules.places => _placeAbbreviations,
    NameRules.addresses => _addressAbbreviations,
  };
  return out
      .toString()
      .split(' ')
      .where((w) => w.isNotEmpty)
      .map((w) => abbreviations[w] ?? w)
      .join(' ');
}

